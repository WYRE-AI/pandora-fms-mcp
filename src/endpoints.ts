  ({ type: "boolean", optional, description });

/** Body fields for a swagger schema (read-only properties already removed). */
function body(schema: keyof typeof SCHEMAS, required: string[] = []): Record<string, ParamSpec> {
  const out: Record<string, ParamSpec> = {};
  for (const [key, spec] of Object.entries(SCHEMAS[schema])) {
    out[key] = required.includes(key) ? { ...spec, optional: false } : { ...spec };
  }
  return out;
}

